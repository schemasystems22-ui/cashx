export const dictionaries: Record<Lang, Record<TKey, string>> = { ar, en };

export type Translate = (key: TKey, vars?: Record<string, string | number>) => string;

export function createTranslator(lang: Lang): Translate {
  const dict = dictionaries[lang];
  return (key, vars) => {
    const template = dict[key] ?? ar[key] ?? key;
    if (!vars) return template;
    return template.replace(/\{(\w+)\}/g, (match, name: string) =>
      name in vars ? String(vars[name]) : match,
    );
  };
}

